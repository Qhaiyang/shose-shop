// ============================================================================
// 图片数组的纯操作
//
// 商品图片在后台里用「上移 / 下移」调整顺序，本质就是把数组里的某个
// 元素插到另一个位置。抽成纯函数、不碰 React、不碰数据库，是为了能
// 直接写单元测试 —— 「顺序调没调对」点页面也能验，但边界情况
// （移第一个、移最后一个、传越界的下标）只有写进测试才记得全。
// ============================================================================

/**
 * 把 `items` 里下标 from 的元素挪到 to，返回一个新数组，不改原数组。
 *
 * 【为什么越界 / 位置不变时原样返回，而不是抛错】
 * 调用方（图片编辑器）已经在按钮上把「第一个不能再上移」这类情况禁用掉了，
 * 这里的越界保护是第二道闸 —— 防线越往里越不该假设外面一定拦住了。
 * 直接返回原数组，语义是「这次操作什么都没改变」。
 */
export function moveItem<T>(items: T[], from: number, to: number): T[] {
  if (from === to) return items
  if (from < 0 || from >= items.length) return items
  if (to < 0 || to >= items.length) return items

  const next = [...items]
  const [item] = next.splice(from, 1)
  next.splice(to, 0, item)
  return next
}
