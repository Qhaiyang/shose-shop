// ============================================================================
// 自然日的边界
//
// 【为什么单独一个文件，而不是用到哪写到哪】
// 「今天」这个词在后台要出现好几次：今日订单数、今日销售额、订单列表按天筛。
// 每处都写一遍 `new Date()` 再 `setHours(0,0,0,0)` 的话，
// 迟早有一处忘了清零 —— 于是那个地方的「今天」悄悄变成了「最近 24 小时」，
// 两个数字对不上，还特别难查（因为两个都「看起来对」）。
//
// 所以边界只在这里定义一次，谁要用谁来取。
//
// 【为什么是本地时间，不是 UTC】
// 店铺的「今天」是店主眼里的今天。服务器跑在哪个时区，
// 店主看到的就该是哪个时区的 00:00。真做跨国生意才需要按「店铺时区」换算，
// 那是另一个问题 —— 学习项目里，本地时间就是正确答案。
//
// 【一个必须知道的坑】
// 数据库里存的是 UTC 时间戳（Prisma 的行为），而这里算出来的是本地时间。
// 看起来矛盾，其实不是：Date 对象本身只是「一个绝对时刻」，
// 「本地时间」这个说法体现在 getHours() / setHours() 这类方法上。
// setHours(0,0,0,0) 的意思是「取这个时刻所在自然日的零点」，
// 拿它去和数据库比大小，比的是时刻，完全一致。
// ============================================================================

/** 把时刻抹到它所在自然日的 00:00:00.000 */
export function startOfDay(date: Date): Date {
  const copy = new Date(date)
  copy.setHours(0, 0, 0, 0)
  return copy
}

/**
 * 明天 00:00。
 *
 * 【为什么用 setDate(+1) 而不是 setHours(24)】
 * setHours(24) 也能得到明天的零点，但它绕了一圈 ——
 * 万一哪天有人手贱把 setHours(0,0,0,0) 挪走，这个就变成「24 小时后」，
 * 而不是「明天零点」，语义就错了。setDate(getDate() + 1) 直说意图。
 *
 * 顺带一提：月末、年末、闰年这些边界，Date 自己会算对
 * （1 月 31 日 + 1 天 = 2 月 1 日，2 月 28 日 + 1 天看是不是闰年），
 * 别自己写 `if (month === 12)`。
 */
export function startOfTomorrow(now: Date = new Date()): Date {
  const copy = startOfDay(now)
  copy.setDate(copy.getDate() + 1)
  return copy
}

/**
 * 把时刻推到它所在自然日的 23:59:59.999。
 *
 * 【为什么需要「一天的最后一毫秒」】
 * 优惠券的截止日期是**按天**填的（活动做到 10 月 31 日）。存成
 * 「10 月 31 日 00:00」的话，这张券在 10 月 31 日零点整就失效了 ——
 * 上午来的用户会发现券没了，而管理员明明写着「到 31 号」。
 * 所以截止日期要落到那一天的最后一毫秒。
 *
 * 【和 todayRange 的左闭右开是什么关系】
 * 两者解决的是同一个问题的两面：区间要能严丝合缝地接起来。
 * 查询用左闭右开（[昨天, 今天) 和 [今天, 明天) 不重不漏）；
 * 而这里是「一个截止时刻」，用当天的最后一毫秒表达，
 * 因为券的规则是简单的 `now <= endAt`，不需要第二个边界。
 */
export function endOfDay(date: Date): Date {
  const copy = new Date(date)
  copy.setHours(23, 59, 59, 999)
  return copy
}

/**
 * 今天的半开区间：[今天 00:00, 明天 00:00)。
 *
 * 【为什么是左闭右开，而不是 `gte 00:00` + `lte 23:59:59`】
 * 时间戳的精度是毫秒。写 lte 23:59:59 的话，
 * 23:59:59.500 下的那笔单两个区间都不算 —— 这一天凭空少了几百毫秒。
 * 用「左闭右开」就没有这个缝：任何一个毫秒值都恰好落在一个区间里，
 * 一天天接起来不重不漏。这是处理时间区间时的通用写法。
 *
 * 【now 参数是给测试用的】
 * 不传就是「现在」。传进去一个固定时刻，就能写出
 * 「2026-03-01 15:00 时今天是几号到几号」这种断言 —— 否则测试
 * 只能在跨零点的那一瞬间跑，那等于没测。
 */
export function todayRange(now: Date = new Date()): { gte: Date; lt: Date } {
  return { gte: startOfDay(now), lt: startOfTomorrow(now) }
}
